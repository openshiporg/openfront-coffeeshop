import { readFile } from "node:fs/promises";
import path from "node:path";
import { buildSchema, Kind, parse, print, validate, validateSchema } from "graphql";
import type { DocumentNode, FieldDefinitionNode, GraphQLSchema } from "graphql";
import { coffeeBoundaryTypeDefs } from "./coffeeBoundarySchema";

const GENERATED_SCHEMA_HEADER = "# This file is automatically generated by Keystone, do not modify it manually.";
const BUNDLED_BOUNDARY_MARKER = "var coffeeBoundaryTypeDefs = String.raw`";

// This is an inventory of client documents to check, not a duplicate GraphQL contract.
export const COFFEE_CLIENT_OPERATION_INVENTORY = [
  { key: "orders", sourcePath: "features/platform/orders/screens/OrderListPage.tsx", constantName: "ORDER_QUERY", operationName: "CoffeeOrderQueue" },
  { key: "kds", sourcePath: "features/platform/kds/screens/KdsPage.tsx", constantName: "KDS_QUERY", operationName: "CoffeeKdsBoard" },
  { key: "operations", sourcePath: "features/platform/coffee-operations/screens/CoffeeOperationsPage.tsx", constantName: "coffeeOperationsQuery", operationName: "CoffeeOperationsPage" },
  { key: "reports", sourcePath: "features/platform/reports/screens/CafeReportsPage.tsx", constantName: "REPORTS_QUERY", operationName: "CoffeeReports" },
] as const;

export type CoffeeClientDocument = {
  key: string;
  sourcePath: string;
  constantName: string;
  operationName: string;
  document: string;
};

export type CoffeeContractPreflightReport = {
  ok: boolean;
  expectedDocumentCount: number;
  extractedDocumentCount: number;
  diagnostics: string[];
};

function isEscaped(source: string, index: number) {
  let backslashes = 0;
  for (let cursor = index - 1; cursor >= 0 && source[cursor] === "\\"; cursor -= 1) backslashes += 1;
  return backslashes % 2 === 1;
}

export function extractStaticGraphqlTemplate(source: string, sourcePath: string, constantName: string) {
  const escapedName = constantName.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const declarationPattern = new RegExp(`\\bconst\\s+${escapedName}\\s*=\\s*`, "g");
  const matches = [...source.matchAll(declarationPattern)];
  if (matches.length !== 1) {
    return { document: null, diagnostic: `${sourcePath}: expected exactly one static ${constantName} GraphQL template; found ${matches.length}` };
  }
  const marker = matches[0];
  const contentStart = marker.index! + marker[0].length;
  if (source[contentStart] !== "`") {
    return { document: null, diagnostic: `${sourcePath}: ${constantName} is not a static template literal; preflight cannot validate the complete document` };
  }

  let end = contentStart + 1;
  for (; end < source.length; end += 1) {
    if (source[end] === "`" && !isEscaped(source, end)) break;
    if (source[end] === "$" && source[end + 1] === "{" && !isEscaped(source, end)) {
      return { document: null, diagnostic: `${sourcePath}: ${constantName} uses unsupported dynamic template interpolation; preflight cannot validate the complete document` };
    }
  }
  if (end >= source.length) {
    return { document: null, diagnostic: `${sourcePath}: ${constantName} has an unterminated GraphQL template` };
  }
  const document = source.slice(contentStart + 1, end).trim();
  if (!document) return { document: null, diagnostic: `${sourcePath}: ${constantName} is an empty GraphQL document` };
  return { document, diagnostic: null };
}

export async function loadCoffeeClientDocuments(rootDir: string) {
  const documents: CoffeeClientDocument[] = [];
  const diagnostics: string[] = [];
  for (const spec of COFFEE_CLIENT_OPERATION_INVENTORY) {
    const sourcePath = path.resolve(rootDir, spec.sourcePath);
    let source: string;
    try {
      source = await readFile(sourcePath, "utf8");
    } catch {
      diagnostics.push(`${spec.sourcePath}: expected client document source is missing or unreadable`);
      continue;
    }
    const extracted = extractStaticGraphqlTemplate(source, spec.sourcePath, spec.constantName);
    if (!extracted.document) {
      diagnostics.push(extracted.diagnostic!);
      continue;
    }
    documents.push({ ...spec, document: extracted.document });
  }
  return { documents, diagnostics };
}

function embeddedBoundarySDL(configText: string) {
  const start = configText.indexOf(BUNDLED_BOUNDARY_MARKER);
  if (start < 0 || configText.indexOf(BUNDLED_BOUNDARY_MARKER, start + BUNDLED_BOUNDARY_MARKER.length) >= 0) {
    return { sdl: null, diagnostic: ".keystone/config.js: expected exactly one compiled coffeeBoundaryTypeDefs artifact" };
  }
  const contentStart = start + BUNDLED_BOUNDARY_MARKER.length;
  const end = configText.indexOf("`;", contentStart);
  if (end < 0) return { sdl: null, diagnostic: ".keystone/config.js: compiled coffeeBoundaryTypeDefs artifact is malformed or unterminated" };
  return { sdl: configText.slice(contentStart, end), diagnostic: null };
}

type ObjectContract = { fields: Map<string, FieldDefinitionNode> };

function objectContracts(document: DocumentNode) {
  const contracts = new Map<string, ObjectContract>();
  for (const definition of document.definitions) {
    if (definition.kind !== Kind.OBJECT_TYPE_DEFINITION && definition.kind !== Kind.OBJECT_TYPE_EXTENSION) continue;
    const name = definition.name.value;
    const contract = contracts.get(name) ?? { fields: new Map<string, FieldDefinitionNode>() };
    for (const field of definition.fields ?? []) contract.fields.set(field.name.value, field);
    contracts.set(name, contract);
  }
  return contracts;
}

function compareBoundarySDL(sourceSDL: string, artifactSDL: string, artifactName: string) {
  const diagnostics: string[] = [];
  let sourceDocument: DocumentNode;
  let artifactDocument: DocumentNode;
  try {
    sourceDocument = parse(sourceSDL);
  } catch (error) {
    return [`features/keystone/mutations/coffeeBoundarySchema.ts: malformed source SDL (${error instanceof Error ? error.message : "parse failure"})`];
  }
  try {
    artifactDocument = parse(artifactSDL);
  } catch (error) {
    return [`${artifactName}: malformed embedded SDL (${error instanceof Error ? error.message : "parse failure"})`];
  }

  const sourceObjects = objectContracts(sourceDocument);
  const artifactObjects = objectContracts(artifactDocument);
  for (const [typeName, sourceType] of sourceObjects) {
    const artifactType = artifactObjects.get(typeName);
    if (!artifactType) {
      diagnostics.push(`${artifactName}: missing type ${typeName}`);
      continue;
    }
    for (const [fieldName, sourceField] of sourceType.fields) {
      const artifactField = artifactType.fields.get(fieldName);
      if (!artifactField) {
        diagnostics.push(`${artifactName}: missing field ${typeName}.${fieldName}`);
        continue;
      }
      const expectedType = print(sourceField.type);
      const actualType = print(artifactField.type);
      if (actualType !== expectedType) diagnostics.push(`${artifactName}: ${typeName}.${fieldName} has type ${actualType}; expected ${expectedType}`);
      const artifactArgs = new Map((artifactField.arguments ?? []).map((argument) => [argument.name.value, argument]));
      for (const sourceArg of sourceField.arguments ?? []) {
        const artifactArg = artifactArgs.get(sourceArg.name.value);
        if (!artifactArg) {
          diagnostics.push(`${artifactName}: missing argument ${typeName}.${fieldName}(${sourceArg.name.value}:)`);
          continue;
        }
        const expectedArgType = print(sourceArg.type);
        const actualArgType = print(artifactArg.type);
        if (actualArgType !== expectedArgType) diagnostics.push(`${artifactName}: ${typeName}.${fieldName}(${sourceArg.name.value}:) has type ${actualArgType}; expected ${expectedArgType}`);
        const expectedDefault = sourceArg.defaultValue ? print(sourceArg.defaultValue) : null;
        const actualDefault = artifactArg.defaultValue ? print(artifactArg.defaultValue) : null;
        if (actualDefault !== expectedDefault) diagnostics.push(`${artifactName}: ${typeName}.${fieldName}(${sourceArg.name.value}:) has default ${actualDefault ?? "<none>"}; expected ${expectedDefault ?? "<none>"}`);
      }
    }
  }
  return diagnostics;
}

function validateDocuments(schema: GraphQLSchema, documents: readonly CoffeeClientDocument[]) {
  const diagnostics: string[] = [];
  if ((COFFEE_CLIENT_OPERATION_INVENTORY as readonly unknown[]).length === 0) {
    diagnostics.push("client operation inventory is empty; refusing a vacuous contract pass");
    return diagnostics;
  }
  if (documents.length !== COFFEE_CLIENT_OPERATION_INVENTORY.length) {
    diagnostics.push(`client document extraction incomplete: expected ${COFFEE_CLIENT_OPERATION_INVENTORY.length}, extracted ${documents.length}`);
  }
  const byKey = new Map(documents.map((document) => [document.key, document]));
  if (byKey.size !== documents.length) diagnostics.push("client document extraction returned duplicate inventory keys");

  for (const expected of COFFEE_CLIENT_OPERATION_INVENTORY) {
    const clientDocument = byKey.get(expected.key);
    if (!clientDocument) {
      diagnostics.push(`${expected.sourcePath}#${expected.constantName}: expected client document was not extracted`);
      continue;
    }
    let document: DocumentNode;
    try {
      document = parse(clientDocument.document);
    } catch (error) {
      diagnostics.push(`${expected.sourcePath}#${expected.constantName}: malformed GraphQL document (${error instanceof Error ? error.message : "parse failure"})`);
      continue;
    }
    const operations = document.definitions.filter((definition) => definition.kind === Kind.OPERATION_DEFINITION);
    if (operations.length !== 1 || operations[0]?.name?.value !== expected.operationName) {
      const actual = operations.map((operation) => operation.name?.value ?? "<anonymous>").join(", ") || "none";
      diagnostics.push(`${expected.sourcePath}#${expected.constantName}: expected exactly operation ${expected.operationName}; found ${actual}`);
      continue;
    }
    for (const error of validate(schema, document)) diagnostics.push(`${expected.sourcePath}#${expected.constantName}: ${error.message}`);
  }
  return diagnostics;
}

export function inspectGeneratedArtifacts(input: {
  schemaSDL: string | null;
  compiledConfig: string | null;
  sourceBoundarySDL?: string;
  documents: readonly CoffeeClientDocument[];
  extractionDiagnostics?: readonly string[];
}): CoffeeContractPreflightReport {
  const diagnostics = [...(input.extractionDiagnostics ?? [])];
  const sourceSDL = input.sourceBoundarySDL ?? coffeeBoundaryTypeDefs;
  let schema: GraphQLSchema | null = null;

  if (input.schemaSDL === null || !input.schemaSDL.trim()) {
    diagnostics.push("schema.graphql: generated SDL is missing or empty");
  } else {
    if (!input.schemaSDL.startsWith(GENERATED_SCHEMA_HEADER)) diagnostics.push("schema.graphql: missing Keystone generated-artifact header; source-only/minimal SDL cannot satisfy this preflight");
    try {
      schema = buildSchema(input.schemaSDL);
      for (const error of validateSchema(schema)) diagnostics.push(`schema.graphql: invalid generated schema: ${error.message}`);
      if (!schema.getType("User") || !schema.getQueryType()?.getFields().authenticatedItem) {
        diagnostics.push("schema.graphql: missing Keystone application sentinels (User and Query.authenticatedItem)");
      }
      diagnostics.push(...compareBoundarySDL(sourceSDL, input.schemaSDL, "schema.graphql"));
    } catch (error) {
      diagnostics.push(`schema.graphql: malformed generated SDL (${error instanceof Error ? error.message : "parse failure"})`);
    }
  }

  if (input.compiledConfig === null || !input.compiledConfig.trim()) {
    diagnostics.push(".keystone/config.js: compiled Keystone config is missing or empty");
  } else {
    const embedded = embeddedBoundarySDL(input.compiledConfig);
    if (embedded.diagnostic) diagnostics.push(embedded.diagnostic);
    else diagnostics.push(...compareBoundarySDL(sourceSDL, embedded.sdl!, ".keystone/config.js"));
  }

  if (input.documents.length === 0) diagnostics.push("client document extraction produced zero documents; refusing a vacuous pass");
  if (schema) diagnostics.push(...validateDocuments(schema, input.documents));
  else if (input.documents.length > 0) diagnostics.push("client documents were not validated because schema.graphql did not produce a usable GraphQL schema");

  const expectedDocumentCount = COFFEE_CLIENT_OPERATION_INVENTORY.length;
  return {
    ok: diagnostics.length === 0 && input.documents.length === expectedDocumentCount,
    expectedDocumentCount,
    extractedDocumentCount: input.documents.length,
    diagnostics,
  };
}

export async function runCoffeeGeneratedContractPreflight(rootDir = process.cwd()): Promise<CoffeeContractPreflightReport> {
  const schemaPath = path.resolve(rootDir, "schema.graphql");
  const configPath = path.resolve(rootDir, ".keystone/config.js");
  const [schemaResult, configResult, clients] = await Promise.all([
    readFile(schemaPath, "utf8").catch(() => null),
    readFile(configPath, "utf8").catch(() => null),
    loadCoffeeClientDocuments(rootDir),
  ]);
  return inspectGeneratedArtifacts({
    schemaSDL: schemaResult,
    compiledConfig: configResult,
    sourceBoundarySDL: coffeeBoundaryTypeDefs,
    documents: clients.documents,
    extractionDiagnostics: clients.diagnostics,
  });
}

if (process.argv[1] && path.resolve(process.argv[1]).endsWith(`${path.sep}coffeeGeneratedContractPreflight.ts`)) {
  void runCoffeeGeneratedContractPreflight().then((report) => {
    console.log(`Coffee generated-contract preflight: ${report.ok ? "PASS" : "FAIL"} (${report.extractedDocumentCount}/${report.expectedDocumentCount} client documents)`);
    for (const diagnostic of report.diagnostics) console.error(` - ${diagnostic}`);
    if (!report.ok) process.exitCode = 1;
  }).catch((error) => {
    console.error(`Coffee generated-contract preflight: FAIL (${error instanceof Error ? error.message : "unexpected failure"})`);
    process.exitCode = 1;
  });
}
